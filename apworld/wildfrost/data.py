"""
The base game's content, read from base.wildfrost.json: the same layout as a mod's extension file
(PLAN.md §10; the user's call, 2026-11-15), generated by tools/gen_data.py from data/content_dump.txt.
It ships inside wildfrost.apworld (pkgutil reads it from the zip), so players still install one file.

The file nests its sections (the user's layout, 2026-11-15): cards by kind then clan, ap_items by kind,
ap_locations as battles and challenges, and their "#2" checks as references ("twins", "spares"). The tables here keep the flat shapes the rest of the apworld uses:
  LOCATIONS, ITEMS: (key, display name, id, info). The key is what the client matches against game
    data (sent in slot_data); the display name is what players see.
  CARDS: (key, display name, info), the cards packs are filled with (not items themselves); info has
    the card's kind, clan and what it applies ("applies").
  LEADERS: each clan's leaders and what they apply.
  BELLS: (game name, storm points, title), the storm bells.
  GROUPS: named card groups the challenge rules use ("any_card", "two_of", "with").
Each challenge row also carries its rule, region and filler-only flag, hand-written in the file (PLAN.md
§10, phase 2): gen_data.py keeps them when it regenerates.
"""

import json
import pkgutil

BASE_FILE = "base.wildfrost.json"
KIND_OF_SECTION = {"companions": "Companion", "items": "Item", "charms": "Charm"}

_doc = json.loads(pkgutil.get_data(__package__ or __name__, BASE_FILE).decode("utf-8"))


def _row(entry: dict, **extra) -> tuple:
    info = {**extra, **{k: v for k, v in entry.items() if k not in ("key", "name", "id")}}
    return entry["key"], entry["name"], entry["id"], info


def _locations(section: dict) -> list:
    """
    The checks: battles and challenges, then each "#2" (twins always come with their original, spares only
    when a seed needs room), made from its original's row: "<key>#2", "<name> #2", same info.
    """
    firsts = [_row(e) for kind in ("battles", "challenges") for e in section.get(kind, [])]
    by_key = {row[0]: row for row in firsts}
    seconds = [(key + "#2", by_key[key][1] + " #2", loc_id, {**by_key[key][3], "second": True, **({"spare": True} if spare else {})})
               for kind, spare in (("twins", False), ("spares", True)) for key, loc_id in section.get(kind, {}).items()]
    return firsts + seconds


LOCATIONS = _locations(_doc["ap_locations"])
ITEMS = [_row(e, kind=kind) for kind, rows in _doc["ap_items"].items() for e in rows]
CARDS = sorted(((e["key"], e["name"], {"kind": KIND_OF_SECTION[section], "clan": clan,
                                       **{k: v for k, v in e.items() if k not in ("key", "name")}})
                for section, clans in _doc["cards"].items() for clan, entries in clans.items() for e in entries),
               key=lambda row: row[0])
LEADERS: dict[str, list[dict]] = {clan: list(leaders) for clan, leaders in _doc.get("leaders", {}).items()}
BELLS = [(b["name"], b["points"], b["title"]) for b in _doc["bells"]]
GROUPS: dict[str, list[str]] = {g: list(v) for g, v in _doc.get("groups", {}).items()}


def _check_logic(logic: dict) -> dict:
    """
    The logic section (PLAN.md §10, phase 3): kits, storm bell steps, goals, forcing and Reverse, written by
    hand. Checked here so a slip fails when the apworld loads rather than partway through a generation.
    """
    kits, bells = logic["kits"], logic["storm_bells"]
    for name, alternatives in kits.items():
        assert alternatives and all(set(a) <= {"companions", "items", "charms"} for a in alternatives), name
    named = [logic["battles"]["kit"], logic["battles"]["true_final_kit"], logic["reverse"]["true_final_kit"],
             *logic["regions"].values(), *(g["kit"] for g in logic["goals"].values()),
             *(step["kit"] for step in logic["forcing"]["kits"])]
    assert all(kit in kits for kit in named), [kit for kit in named if kit not in kits]
    assert bells["levels"] * bells["points_per_level"] == bells["overcrank_points"]
    assert all(len(row) == bells["levels"] + 1 for row in logic["reverse"]["stretches"].values())
    assert logic["forcing"]["kits"][-1]["up_to_points"] >= bells["overcrank_points"]
    return logic


LOGIC: dict = _check_logic(_doc["logic"])
